#!/usr/bin/env python3
"""Writes internal/search/fold_table.go: the first code point of each
character's full Unicode case folding, where it differs from the character,
as libnu's nu_tofold gives RediSearch's suggestion trie."""
import sys, unicodedata

pairs = []
for c in range(0x110000):
    if 0xD800 <= c <= 0xDFFF:
        continue
    f = ord(chr(c).casefold()[0])
    if f != c:
        pairs.append((c, f))
out = sys.stdout
out.write("// Code generated by scripts/gen_fold_table.py from Unicode %s; DO NOT EDIT.\n\n" % unicodedata.unidata_version)
out.write("package search\n\n")
out.write("// foldTable maps a code point to the first code point of its full case\n// folding, for the code points it changes, sorted.\n")
out.write("var foldTable = [...][2]uint32{\n")
for i in range(0, len(pairs), 5):
    out.write("\t" + " ".join("{0x%04X, 0x%04X}," % p for p in pairs[i:i+5]) + "\n")
out.write("}\n")
